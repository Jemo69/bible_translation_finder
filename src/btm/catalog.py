"""Curated catalog of Bible translations.

Each entry describes where the full text can be fetched from:

- ``source_type="open-bibles"`` — a file in the seven1m/open-bibles GitHub
  repo (OSIS, USFX, or Zefania XML).
- ``source_type="ebible"`` — a ``*_usfx.zip`` archive on eBible.org. Every
  ``ebible`` entry below is marked ``Redistributable`` in the eBible.org
  catalog, i.e. it may be freely downloaded and redistributed.
- ``source_type="youversion"`` — scraped chapter-by-chapter from bible.com
  for personal use (slow; prefer the other sources when available).
- ``source_type=None`` — copyrighted work with no free source; downloads
  produce a stub file pointing at the publisher.

Use :func:`search_catalog` to find translations offline (no network), or
:func:`get_catalog` for the whole list.
"""

