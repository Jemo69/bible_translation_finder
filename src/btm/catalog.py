def get_catalog():
    return POPULAR_TRANSLATIONS


def get_translation(translation_id: str):
    for t in POPULAR_TRANSLATIONS:
        if t["id"] == translation_id:
            return t
    return None


def get_by_abbreviation(abbreviation: str):
    """Find a translation by abbreviation (case-insensitive) or id."""
    if not abbreviation:
        return None
    key = abbreviation.strip().lower()
    for t in POPULAR_TRANSLATIONS:
        if t["abbreviation"].lower() == key or t.get("id", "").lower() == key:
            return t
    return None


def search_catalog(query: str = "", language: str = ""):
    """Offline search of the curated catalog by name/abbreviation/language."""
    q = (query or "").strip().lower()
    lang = (language or "").strip().lower()
    results = []
    for t in POPULAR_TRANSLATIONS:
        hay = " ".join(
            str(t.get(k, "")) for k in ("abbreviation", "name", "id", "language")
        ).lower()
        if q and q not in hay:
            continue
        if lang and lang not in t.get("language", "").lower():
            continue
        results.append(t)
    return sorted(results, key=lambda t: t.get("popularity_rank", 99))


def list_languages():
    """Sorted list of language names covered by the catalog."""
    return sorted({t.get("language", "") for t in POPULAR_TRANSLATIONS if t.get("language")})


def get_freely_available():
    return [t for t in POPULAR_TRANSLATIONS if t["freely_available"]]


def get_copyrighted():
    return [t for t in POPULAR_TRANSLATIONS if not t["freely_available"]]
